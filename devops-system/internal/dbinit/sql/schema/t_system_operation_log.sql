-- t_system_operation_log 操作审计表（租户表）：B 端管理写操作审计。
-- 列宽与 devops-common/audit 契约常量一一对应。
CREATE TABLE IF NOT EXISTS t_system_operation_log (
    id             BIGINT       NOT NULL,
    creator        VARCHAR(64)  NULL,
    create_time    DATETIME(3)  NULL,
    updater        VARCHAR(64)  NULL,
    update_time    DATETIME(3)  NULL,
    deleted_at     DATETIME(3)  NULL,
    tenant_id      BIGINT       NOT NULL,
    trace_id       VARCHAR(100) NOT NULL DEFAULT '',
    user_id        BIGINT       NOT NULL DEFAULT 0,
    user_name      VARCHAR(30)  NOT NULL DEFAULT '',
    user_type      BIGINT       NOT NULL DEFAULT 0,
    module         VARCHAR(50)  NOT NULL DEFAULT '',
    sub_module     VARCHAR(50)  NOT NULL DEFAULT '',
    biz_id         BIGINT       NOT NULL DEFAULT 0,
    contents       TEXT         NULL,
    extra          TEXT         NULL,
    request_method VARCHAR(16)  NOT NULL DEFAULT '',
    request_url    VARCHAR(255) NOT NULL DEFAULT '',
    user_ip        VARCHAR(50)  NOT NULL DEFAULT '',
    user_agent     VARCHAR(512) NOT NULL DEFAULT '',
    geo_country    VARCHAR(64)  NOT NULL DEFAULT '',
    geo_province   VARCHAR(64)  NOT NULL DEFAULT '',
    geo_city       VARCHAR(64)  NOT NULL DEFAULT '',
    geo_isp        VARCHAR(64)  NOT NULL DEFAULT '',
    result         TINYINT      NOT NULL DEFAULT 0,
    code           BIGINT       NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_t_system_operation_log_deleted_at (deleted_at),
    KEY idx_t_system_operation_log_tenant_id (tenant_id),
    KEY idx_t_system_operation_log_trace_id (trace_id),
    KEY idx_t_system_operation_log_user_id (user_id),
    KEY idx_t_system_operation_log_user_name (user_name),
    KEY idx_t_system_operation_log_module (module),
    KEY idx_t_system_operation_log_sub_module (sub_module),
    KEY idx_t_system_operation_log_user_ip (user_ip)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
